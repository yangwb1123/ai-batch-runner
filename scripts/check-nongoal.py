#!/usr/bin/env python3
"""Non-goal restraint gate (L6, pure stdlib): directions/artifacts that
collide with the project's explicit non-goals fail closed.

iris-ui's ROADMAP "明确不做" (QRCode / first npm publish / v3 architecture)
stopped agents from auto-starting maintainer-decision work; snaplink's
"不应被前端复制的协议能力" defined the interface boundary. This gate
mechanically blocks claims/directions that cross the project's own
explicit_non_goals list.

Constitution source (searched in order):
  1. --constitution FILE (explicit)
  2. DIR/docs/evolution/constitution.yaml (generated by `pi-batch
     evolution init`)
  3. DIR/evolution.yaml (project-root declaration)

Constitution shape:
    explicit_non_goals:
      - "不在浏览器内重新实现 Token/签名"
      - "未经维护者授权不执行首次 npm 发布"

A claim is flagged when an artifact line mentions the same keywords as a
non-goal. The gate is FAIL-CLOSED by default (missing constitution is a
warning, not a pass): without a constitution the gate reports
"no constitution" and exits 0 with an explicit stderr warning — it never
pretends a boundary exists where none was declared (vacuous-green ban).

Usage:
    python scripts/check-nongoal.py <artifact> [--dir PROJECT_ROOT]
                                     [--constitution FILE] [--json]
Register as validator: nongoal = "python {cwd}/scripts/check-nongoal.py {output}"
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

CONSTITUTION_NAMES = ("docs/evolution/constitution.yaml", "evolution.yaml")


def _yaml_goals(text: str, text_goals: list) -> list:
    """PyYAML 解析 explicit_non_goals（无 YAML 时返回空）。"""
    try:
        import yaml
    except ImportError:
        return []
    try:
        data = yaml.safe_load(text)
        raw = (data or {}).get("explicit_non_goals") or []
        if isinstance(raw, list):
            return [str(g) for g in raw if str(g).strip()]
    except Exception:
        return []
    return text_goals


def _plain_goals(text: str) -> list:
    """纯子集回退：解析 explicit_non_goals 下的 '- ' 行。"""
    goals, capture = [], False
    for line in text.splitlines():
        stripped = line.strip()
        if stripped.startswith("explicit_non_goals"):
            capture = True
            continue
        if capture and stripped.startswith("- "):
            goals.append(stripped[2:].strip())
        elif capture and not stripped.startswith("#") and stripped:
            break
    return goals


def _load_constitution(dir_path: Path, explicit: str = "") -> tuple:
    """Return (goals: list, source: str)."""
    candidates = []
    if explicit:
        candidates.append((Path(explicit).resolve(), explicit))
    for name in CONSTITUTION_NAMES:
        candidate = dir_path / name
        if candidate.is_file():
            candidates.append((candidate, str(candidate)))
    for path, label in candidates:
        try:
            text = path.read_text(encoding="utf-8")
        except OSError:
            continue
        goals = _yaml_goals(text, [])
        if not goals:
            goals = _plain_goals(text)
        if goals:
            return goals, label
    return [], ""


def _keyword_terms(goal: str) -> list:
    """Extract matching terms from a non-goal phrase (Chinese/English)."""
    import re
    terms = [t.strip(" '\"`.,;:()[]{}") for t in re.split(r"[/，。；、\s]+", goal)
             if len(t.strip(" '\"`.,;:()[]{}")) >= 2]
    return terms


def check_artifact(text: str, goals: list) -> dict:
    findings = []
    lines = text.splitlines()
    for idx, line in enumerate(lines, start=1):
        lowered = line.lower()
        for goal in goals:
            terms = _keyword_terms(goal)
            hits = [t for t in terms if t.lower() in lowered]
            # 至少 2 个关键词命中，或 1 个强命中（≥4 字长中文词 /
            # ≥6 字符英文词），避免单词误撞（如 "Token"）。
            strong = [t for t in hits
                      if (any("\u4e00" <= c <= "\u9fff" for c in t) and len(t) >= 4)
                      or (not any("\u4e00" <= c <= "\u9fff" for c in t)
                          and len(t) >= 6)]
            if len(hits) >= 2 or strong:
                findings.append({
                    "line": idx, "kind": "non_goal_collision",
                    "goal": goal, "matched": hits[:5],
                    "text": line.strip()[:120],
                    "fix_hint": f"collides with explicit non-goal: {goal}"})
                break
    return {"collisions": findings}


def main(argv: list) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("artifact", help="artifact (direction/claim) to check")
    parser.add_argument("--dir", default=".", help="project root (constitution search)")
    parser.add_argument("--constitution", default="", help="explicit constitution file")
    parser.add_argument("--json", action="store_true", help="emit machine JSON")
    args = parser.parse_args(argv)

    artifact = Path(args.artifact)
    if not artifact.is_file():
        print(f"check-nongoal: artifact not found: {artifact}", file=sys.stderr)
        return 1
    goals, source = _load_constitution(Path(args.dir).resolve(), args.constitution)
    report = check_artifact(artifact.read_text(encoding="utf-8", errors="replace"),
                            goals)
    report["constitution"] = source
    report["non_goals"] = len(goals)
    if args.json:
        print(json.dumps(report, ensure_ascii=False))
    if not goals:
        print("check-nongoal: WARN — no explicit_non_goals in constitution "
              "(vacuous-green ban: absent boundary is not a pass signal); "
              "run `pi-batch evolution init` to scaffold one.", file=sys.stderr)
        return 0
    if report["collisions"]:
        for item in report["collisions"]:
            print(f"check-nongoal: L{item['line']} [non_goal_collision] "
                  f"{item['text']} — {item['fix_hint']}", file=sys.stderr)
        print(f"check-nongoal: FAIL — direction collides with explicit non-goal "
              f"({source}); restraint (L6) is a hard boundary.", file=sys.stderr)
        return 1
    print(f"check-nongoal: OK — {len(goals)} non-goal(s) from {source}, no collisions")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
